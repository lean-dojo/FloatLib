#!/usr/bin/env python3
"""Generate complete NVFP4 quantization, decode and stored-dot observations."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "benchmarks/results/standards-matrix/nvfp4"
MODULE = ROOT / "benchmarks/lean/FloatLibBenchmarks/Standards/NVFP4Matrix.lean"
HEADER = """-- Generated by benchmarks/scripts/nvfp4-matrix.py.
import FloatLibBenchmarks.Standards.NVFP4Inputs
open FloatLib FloatLib.Floats FloatLib.Numerics
open FloatLib.Floats.Formats FloatLib.Floats.Formats.BinaryInterchange
open FloatLibBenchmarks.Standards FloatLibBenchmarks.Standards.NVFP4Inputs
set_option maxRecDepth 100000
"""


def main():
    cases = []

    def add(label, inputs, fixture, expression, declaration, **metadata):
        cases.append(dict(label=label, inputs=inputs, fixture=fixture,
                          expression=expression, declaration=declaration, **metadata))

    for n in [16, 64]:
        for name in ["supplied", "dynamic"]:
            add(f"quantize{n}-{name}",
                f"(List.range 8).toArray.map (MX.vectorInput {n})",
                f"MX.vectorInput {n} 0",
                f"observeTensor ((format {n}).quantize ({name}Policy {n}) s)",
                "FloatLib.Floats.Formats.Block.CodedFormat.quantize",
                positions=n, scale_policy=name)
        add(f"decode{n}", f"(List.range 8).toArray.map (tensorInput {n})",
            f"tensorInput {n} 0", "observeDecoded s",
            "FloatLib.Floats.Formats.Block.Tensor.decode", positions=n)
        for operation in ["Dot", "DotGeneral"]:
            order = f"List.finRange {n}" if operation == "Dot" else f"blocks {n}"
            for name, reduction in [
                ("exact", "Block.Reduction.exact"),
                ("binary16", "Block.Reduction.binary .binary16 "
                 "(Block.Extended.round .binary16)"),
            ]:
                add(f"{operation}{n}-{name}",
                    f"(List.range 8).toArray.map (tensorInput {n})",
                    f"tensorInput {n} 0",
                    f"(OCP.MX.{operation} .binary32 s (tensorInput {n} 0) "
                    f"({order}) ({reduction})).toNatBits",
                    f"FloatLib.Floats.Formats.OCP.MX.{operation}",
                    positions=n, accumulator=name, output_bits=32)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    catalog = dict(
        family="NVFP4", widths=[4], cases=cases,
        limitations=[
            "Width 4 is the E2M1 element width. Each sixteen-position group "
            "has an E4M3 local scale and the tensor has one binary32 outer scale.",
            "The two policies use exact rational scale arithmetic, not the "
            "finite working precision of a vendor implementation.",
            "Complete ordered observations include all stored fields or all decoded "
            "data fields. Observation work is included; no overhead is subtracted.",
            "Dot inputs are stored codes. Exact and binary16 intermediate reduction "
            "are separate; the delivered output is binary32.",
            "Each kernel row uses the first finite native input only. The native "
            "input array also includes exceptional scales.",
        ])
    (OUTPUT / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n")
    lines = ["module\n\n", HEADER]
    for first in range(0, len(cases), 7):
        lines.append(f"private def group{first} (first last : Nat) : IO Unit := do\n")
        for index, case in enumerate(cases[first:first + 7], first):
            lines.append(
                f"  if first ≤ {index} && {index} < last then\n"
                f'    measure "NVFP4" "{case["label"]}" 4 '
                f'({case["inputs"]}) fun s => {case["expression"]}\n')
    lines.append(
        "/-- Run the selected standard timing cases. -/\npublic def main (args : List String) : IO Unit := do\n"
        '  let width := (args[0]?.getD "4").toNat!\n'
        '  if width != 4 then throw (IO.userError "NVFP4 elements have four bits")\n'
        '  let first := (args[1]?.getD "0").toNat!\n'
        f'  let last := (args[2]?.getD "{len(cases)}").toNat!\n')
    lines.extend(f"  group{first} first last\n" for first in range(0, len(cases), 7))
    MODULE.write_text("".join(lines))
    kernel = [HEADER]
    for index, case in enumerate(cases):
        kernel.append(
            f'#print "MATRIX_KERNEL NVFP4 {case["label"]} width=4 case={index}"\n'
            f'#kernel_cost rewritten (let s := {case["fixture"]}; '
            f'{case["expression"]})\n')
    (OUTPUT / "Kernel4.lean").write_text("".join(kernel))
    print(json.dumps(dict(cases=len(cases), widths=[4])))


if __name__ == "__main__":
    main()
