#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
cd "$ROOT"

# shellcheck source=tests/lib/lake.sh
source "$ROOT/tests/lib/lake.sh"

floatlib_benchmark_lake build \
  FloatLibBenchmarks.Codegen.AutomaticSelection \
  FloatLibBenchmarks.Public.Precision

extract_c_body() {
  local file="$1"
  local signature="$2"

  awk -v signature="$signature" '
    index($0, signature) == 1 && index($0, "{") > 0 {
      selected = 1
    }
    selected {
      print
      opens = $0
      closes = $0
      open_count = gsub(/\{/, "{", opens)
      close_count = gsub(/\}/, "}", closes)
      depth += open_count - close_count
      if (open_count > 0) {
        entered = 1
      }
      if (entered && depth == 0) {
        exit
      }
    }
  ' "$file"
}

extract_c_body_by_suffix() {
  local file="$1"
  local suffix="$2"

  # Workload declarations are generated by a hygienic Lean command macro. Lean may therefore
  # insert a private-name component into the C symbol even though the source-level workload name
  # is stable. Match the complete name suffix, including the opening parenthesis, so `p2` cannot
  # accidentally select `p24`, while remaining independent of compiler-generated prefixes.
  awk -v suffix="$suffix" '
    index($0, "LEAN_EXPORT uint64_t ") == 1 &&
        index($0, suffix) > 0 &&
        index($0, "{") > 0 {
      selected = 1
    }
    selected {
      print
      opens = $0
      closes = $0
      open_count = gsub(/\{/, "{", opens)
      close_count = gsub(/\}/, "}", closes)
      depth += open_count - close_count
      if (open_count > 0) {
        entered = 1
      }
      if (entered && depth == 0) {
        exit
      }
    }
  ' "$file"
}

reject_planner_in_body() {
  local label="$1"
  local body="$2"

  if grep -Eq \
      'List_foldl|considerCertified|selectCertified|lean_thunk_get(_own)?' \
      <<< "$body"; then
    printf '%s reruns or forces the planner inside its hot body:\n%s\n' \
      "$label" "$body" >&2
    exit 1
  fi
}

custom_c="$(
  floatlib_build_path ir/FloatLibBenchmarks/Codegen/AutomaticSelection.c
)"
custom_prefix="lp_floatlibBenchmarks_FloatLibBenchmarks_Codegen_AutomaticSelection"

if [[ ! -f "$custom_c" ]]; then
  printf 'missing generated custom-selection C file: %s\n' "$custom_c" >&2
  exit 1
fi

custom_body="$(
  extract_c_body "$custom_c" \
    "LEAN_EXPORT uint8_t ${custom_prefix}_customAddLoop("
)"
if [[ -z "$custom_body" ]]; then
  printf '%s\n' 'missing generated customAddLoop body' >&2
  exit 1
fi
reject_planner_in_body "customAddLoop" "$custom_body"
if ! grep -Fq 'lean_obj_once' <<< "$custom_body"; then
  printf 'customAddLoop does not retrieve a closed memoized selection:\n%s\n' \
    "$custom_body" >&2
  exit 1
fi
if ! grep -Fq 'lean_apply_2' <<< "$custom_body"; then
  printf 'customAddLoop unexpectedly lost its extensible custom-kernel call:\n%s\n' \
    "$custom_body" >&2
  exit 1
fi
if ! grep -Fq 'List_foldl' "$custom_c" || ! grep -Fq 'lean_thunk_get_own' "$custom_c"; then
  printf '%s\n' \
    'custom-selection probe does not contain the expected one-time memoized planner' >&2
  exit 1
fi

precisions=(2 3 4 5 6 7 8 11 24 53 113 161 237 493 1024 2048 4096)
operations=(Add Sub Mul Div Sqrt Fma)

for operation in "${operations[@]}"; do
  generated_c="$(
    floatlib_build_path \
      "ir/FloatLibBenchmarks/Public/Precision.c"
  )"

  if [[ ! -f "$generated_c" ]]; then
    printf 'missing generated precision-sweep C file: %s\n' "$generated_c" >&2
    exit 1
  fi

  for precision in "${precisions[@]}"; do
    function_name="p${precision}"
    body="$(
      extract_c_body_by_suffix "$generated_c" \
        "_FloatLibBenchmarks_Public_Precision_${function_name}${operation}("
    )"
    if [[ -z "$body" ]]; then
      printf 'missing generated %s.%s body\n' "$operation" "$function_name" >&2
      exit 1
    fi
    reject_planner_in_body "${operation}.${function_name}" "$body"
    if ! grep -Fq 'lean_obj_once' <<< "$body"; then
      printf '%s.%s does not retrieve a closed prepared implementation:\n%s\n' \
        "$operation" "$function_name" "$body" >&2
      exit 1
    fi
  done
done

printf '%s\n' \
  'Automatic selection code generation passed: custom and 2 to 4096 bit plans are prepared once, never rescored in hot loops.'
