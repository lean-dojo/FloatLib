#!/usr/bin/env python3
"""Generate complete-result OFP8 timings from one conversion catalog."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "benchmarks/results/standards-matrix/ofp8"
MODULE = ROOT / "benchmarks/lean/FloatLibBenchmarks/Standards/OFP8Matrix.lean"
FORMATS = {
    "binary16": (5, 10, 15),
    "bfloat16": (8, 7, 127),
    "binary32": (8, 23, 127),
    "e4m3": (4, 3, 7),
    "e5m2": (5, 2, 15),
}
DECLARATION = "FloatLib.Floats.Formats.OCP.FP8.convert"
HEADER = """-- Generated by benchmarks/scripts/ofp8-matrix.py.
import FloatLibBenchmarks.Standards.OFP8
open FloatLib FloatLib.Floats FloatLib.Numerics
open FloatLib.Floats.Formats.BinaryInterchange
open FloatLibBenchmarks.Standards FloatLibBenchmarks.Standards.OFP8
set_option maxRecDepth 32768
"""


def main():
    cases = []

    def add(label, source, expression, declaration):
        cases.append(dict(label=label, source=source, expression=expression,
                          declaration=declaration))

    def conversion(source, destination, mode):
        add(f"{source}-to-{destination}-{mode}", source,
            f"observeOutcome Model.toNatBits (Formats.OCP.FP8.convert "
            f".{destination} .{mode} s)", DECLARATION)

    for fp8 in ["e4m3", "e5m2"]:
        add(f"{fp8}-input", fp8, "Model.toNatBits s", None)
        add(f"{fp8}-decode", fp8, "observeDecoded (ExecFloat.ExactDecoder.run s)",
            "FloatLib.Floats.ExecFloat.ExactDecoder.run")
        for source in ["binary16", "bfloat16", "binary32"]:
            for mode in ["native", "saturate"]:
                conversion(source, fp8, mode)
                conversion(fp8, source, mode)
        for mode in ["native", "saturate"]:
            conversion(fp8, "e5m2" if fp8 == "e4m3" else "e4m3", mode)

    OUTPUT.mkdir(parents=True, exist_ok=True)
    MODULE.parent.mkdir(parents=True, exist_ok=True)
    catalog = dict(
        family="OFP8", widths=[8], cases=cases,
        limitations=[
            "OFP8 words have eight bits. Binary16, bfloat16 and binary32 are the "
            "specified source formats. Reverse and cross-format conversions are "
            "instances of the more general FloatLib interface.",
            "Native trials include eight finite and exceptional regimes; each kernel "
            "fixture measures only the same first positive finite word.",
            "Decoding observes the rational numerator, denominator, sign bit and "
            "exceptional metadata directly; observer arithmetic is included.",
            "Conversion observers include every output bit and every diagnostic flag. "
            "These FloatLib flags are not prescribed by OFP8.",
        ])
    (OUTPUT / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n")
    lines = ["module\n\n", HEADER]
    for first in range(0, len(cases), 8):
        lines.append(f"private def group{first} (first last : Nat) : IO Unit := do\n")
        for index, case in enumerate(cases[first:first + 8], first):
            lines.append(
                f'  if first ≤ {index} && {index} < last then\n'
                f'    measure "OFP8" "{case["label"]}" 8 '
                f'((List.range 8).toArray.map (sample .{case["source"]})) '
                f'fun s => {case["expression"]}\n')
    lines.append(
        "/-- Run the selected standard timing cases. -/\npublic def main (args : List String) : IO Unit := do\n"
        '  let width := (args[0]?.getD "8").toNat!\n'
        '  if width != 8 then throw (IO.userError "OFP8 words have eight bits")\n'
        '  let first := (args[1]?.getD "0").toNat!\n'
        f'  let last := (args[2]?.getD "{len(cases)}").toNat!\n')
    lines.extend(f"  group{first} first last\n" for first in range(0, len(cases), 8))
    MODULE.write_text("".join(lines))
    kernel = [HEADER]
    for index, case in enumerate(cases):
        _, fraction, bias = FORMATS[case["source"]]
        word = bias * 2**fraction + 2**fraction // 3 + 1
        kernel.append(
            f'#print "MATRIX_KERNEL OFP8 {case["label"]} width=8 case={index}"\n'
            f'#kernel_cost rewritten (let s : Model .{case["source"]} := '
            f'Model.ofNatBits {word}; {case["expression"]})\n')
    (OUTPUT / "Kernel8.lean").write_text("".join(kernel))
    print(json.dumps(dict(cases=len(cases), widths=[8])))


if __name__ == "__main__":
    main()
