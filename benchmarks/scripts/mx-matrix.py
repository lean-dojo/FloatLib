#!/usr/bin/env python3
"""Generate fixed-profile MX and E8M0 whole-result measurements."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "benchmarks/results/standards-matrix/mx"
MODULE = ROOT / "benchmarks/lean/FloatLibBenchmarks/Standards/MXMatrix.lean"
HEADER = """-- Generated by benchmarks/scripts/mx-matrix.py.
import FloatLibBenchmarks.Standards.MX
open FloatLib FloatLib.Floats FloatLib.Numerics
open FloatLib.Floats.Formats FloatLib.Floats.Formats.BinaryInterchange
open OCP.MX OCP.MX.Standard
open FloatLibBenchmarks.Standards FloatLibBenchmarks.Standards.MX
set_option maxRecDepth 100000
"""


def main():
    cases = []

    def add(label, inputs, fixture, expression, declaration, **metadata):
        cases.append(dict(label=label, inputs=inputs, fixture=fixture,
                          expression=expression, declaration=declaration, **metadata))

    profiles = [("e4m3", 8), ("e5m2", 8), ("e2m3", 6),
                ("e3m2", 6), ("e2m1", 4), ("int8", 8)]
    for profile, bits in profiles:
        for overflow in ["saturate", "native"]:
            add(f"{profile}-element-{overflow}",
                "(List.range 8).toArray.map scalarInput", "scalarInput 0",
                f"(Element.quantize .{profile} s .{overflow}).toNat",
                "FloatLib.Floats.Formats.OCP.MX.Standard.Element.quantize",
                profile=profile, element_bits=bits, positions=1)
        add(f"{profile}-decode",
            f"(List.range 8).toArray.map (fun i => "
            f"BitVec.ofNat {bits} (i * 17 + 3) : Nat → Element .{profile})",
            f"(BitVec.ofNat {bits} 3 : Element .{profile})",
            f"OFP8.observeDecoded (Element.decode (profile := .{profile}) s)",
            "FloatLib.Floats.Formats.OCP.MX.Standard.Element.decode",
            profile=profile, element_bits=bits, positions=1)
        for n in [32, 64]:
            add(f"{profile}-quantize{n}",
                f"(List.range 8).toArray.map (vectorInput {n})",
                f"vectorInput {n} 0",
                f"observeTensor ((format (@group {n}) .{profile}).quantize "
                f"(policy (@group {n}) .{profile}) s)",
                "FloatLib.Floats.Formats.Block.CodedFormat.quantize",
                profile=profile, element_bits=bits, positions=n)
        for n, operation in [(32, "Dot"), (64, "DotGeneral")]:
            order = f"List.finRange {n}" if operation == "Dot" else f"blocks {n}"
            for name, reduction in [
                ("exact", "Block.Reduction.exact"),
                ("binary16", "Block.Reduction.binary .binary16 "
                 "(Block.Extended.round .binary16)"),
            ]:
                add(f"{profile}-{operation}{n}-{name}",
                    f"(List.range 8).toArray.map (tensorInput {n} .{profile})",
                    f"tensorInput {n} .{profile} 0",
                    f"(OCP.MX.{operation} .binary32 s (tensorInput {n} .{profile} 0) "
                    f"({order}) ({reduction})).toNatBits",
                    f"FloatLib.Floats.Formats.OCP.MX.{operation}",
                    profile=profile, element_bits=bits, positions=n,
                    accumulator=name, output_bits=32)

    scale_inputs = "(List.range 8).toArray.map scaleInput"
    prefix = "FloatLib.Floats.Formats.OCP.MX.E8M0."
    add("E8M0-ofNatBits", "#[127, 0, 254, 255, 256, 257, 511, 65535]",
        "(127 : Nat)", "(E8M0.ofNatBits s).toNatBits", prefix + "ofNatBits")
    for operation, expression in [
        ("toNatBits", "s.toNatBits"),
        ("isNaN", "s.isNaN.toNat"),
        ("exponent?", "(s.exponent?).map (fun e => 1 + observeInt e) |>.getD 0"),
        ("toDyadic?", "observeDyadic s.toDyadic?"),
        ("scaleDyadic?", "observeDyadic (s.scaleDyadic? ⟨true, 7, -3⟩)"),
    ]:
        add("E8M0-" + operation, scale_inputs, "scaleInput 0", expression,
            prefix + operation)
    exponent_inputs = "(#[(0 : Int), -127, 127, -128, 128, -4096, 4096, 1])"
    add("E8M0-ofExponent?", exponent_inputs, "(0 : Int)",
        "(E8M0.ofExponent? s).map (fun x => x.toNatBits + 1) |>.getD 0",
        prefix + "ofExponent?")
    add("E8M0-ofExponentSaturating", exponent_inputs, "(0 : Int)",
        "(E8M0.ofExponentSaturating s).toNatBits", prefix + "ofExponentSaturating")

    OUTPUT.mkdir(parents=True, exist_ok=True)
    catalog = dict(
        family="MX", widths=[8], cases=cases,
        limitations=[
            "Width 8 names the fixed E8M0 scale byte, not an eight-bit element "
            "or whole block. Each MX case separately records the actual 4/6/8 "
            "element bits and 1/32/64 positions.",
            "The quantization observation packs every element and scale code in order. "
            "It includes scale selection and the observation cost.",
            "Dot fixtures use stored words with no quantization. Delivered results "
            "are binary32; the exact and binary16 intermediate choices are separate.",
            "Native arrays include finite and exceptional regimes. Each kernel row "
            "uses only the first finite native input; no latency bound is asserted.",
            "E8M0 constructor/encoder helpers are FloatLib operations on the §5.4 "
            "encoding, not eight additional standard-mandated arithmetic operations.",
        ])
    (OUTPUT / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n")
    lines = ["module\n\n", HEADER]
    for first in range(0, len(cases), 8):
        lines.append(f"private def group{first} (first last : Nat) : IO Unit := do\n")
        for index, case in enumerate(cases[first:first + 8], first):
            lines.append(
                f"  if first ≤ {index} && {index} < last then\n"
                f'    measure "MX" "{case["label"]}" 8 '
                f'({case["inputs"]}) fun s => {case["expression"]}\n')
    lines.append(
        "/-- Run the selected standard timing cases. -/\npublic def main (args : List String) : IO Unit := do\n"
        '  let width := (args[0]?.getD "8").toNat!\n'
        '  if width != 8 then throw (IO.userError "MX uses an eight-bit scale")\n'
        '  let first := (args[1]?.getD "0").toNat!\n'
        f'  let last := (args[2]?.getD "{len(cases)}").toNat!\n')
    lines.extend(f"  group{first} first last\n" for first in range(0, len(cases), 8))
    MODULE.write_text("".join(lines))
    kernel = [HEADER]
    for index, case in enumerate(cases):
        kernel.append(
            f'#print "MATRIX_KERNEL MX {case["label"]} width=8 case={index}"\n'
            f'#kernel_cost rewritten (let s := {case["fixture"]}; '
            f'{case["expression"]})\n')
    (OUTPUT / "Kernel8.lean").write_text("".join(kernel))
    print(json.dumps(dict(cases=len(cases), widths=[8])))


if __name__ == "__main__":
    main()
